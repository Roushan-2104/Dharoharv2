// Intelligently resolve the closest regional food profile for any given entity
export const getRegionalFoodsForEntity = (entity) => {
  if (!entity) return REGIONAL_FOOD_DATABASE.puri;

  const nameLower = (entity.name || '').toLowerCase();
  const locLower = (entity.location_context || '').toLowerCase();

  // 1. Puri & Konark Match
  if (
    locLower.includes('puri') || locLower.includes('konark') || 
    locLower.includes('pipili') || nameLower.includes('jagannath') || 
    nameLower.includes('sun temple') || nameLower.includes('raghurajpur')
  ) {
    return REGIONAL_FOOD_DATABASE.puri;
  }

  // 2. Bhubaneswar & Khordha Match
  if (
    locLower.includes('bhubaneswar') || locLower.includes('khordha') || 
    locLower.includes('khurda') || nameLower.includes('lingaraj') || 
    nameLower.includes('dhauli') || nameLower.includes('khandagiri') || 
    nameLower.includes('udayagiri') || nameLower.includes('mukteswar') ||
    nameLower.includes('rajarani') || nameLower.includes('chausath yogini')
  ) {
    return REGIONAL_FOOD_DATABASE.bhubaneswar;
  }

  // 3. Cuttack Match
  if (
    locLower.includes('cuttack') || locLower.includes('kendrapara') || 
    nameLower.includes('barabati') || nameLower.includes('chandi') ||
    nameLower.includes('tarakasi') || nameLower.includes('bali yatra')
  ) {
    return REGIONAL_FOOD_DATABASE.cuttack;
  }

  // 4. Nayagarh Match
  if (
    locLower.includes('nayagarh') || locLower.includes('ranpur') || 
    locLower.includes('kantilo') || locLower.includes('daspalla') ||
    nameLower.includes('nilamadhaba')
  ) {
    return REGIONAL_FOOD_DATABASE.nayagarh;
  }

  // 5. Sambalpur & Western Odisha Match
  if (
    locLower.includes('sambalpur') || locLower.includes('bargarh') || 
    locLower.includes('balangir') || locLower.includes('bolangir') ||
    locLower.includes('jharsuguda') || locLower.includes('kalahandi') ||
    locLower.includes('sonepur') || locLower.includes('subarnapur') ||
    nameLower.includes('samaleswari') || nameLower.includes('hirakud') ||
    nameLower.includes('nrusinghanath') || nameLower.includes('dhanu yatra')
  ) {
    return REGIONAL_FOOD_DATABASE.sambalpur;
  }

  // 6. Mayurbhanj & Northern Odisha Match
  if (
    locLower.includes('mayurbhanj') || locLower.includes('baripada') || 
    locLower.includes('keonjhar') || locLower.includes('sundargarh') ||
    nameLower.includes('belgadia') || nameLower.includes('khiching') ||
    nameLower.includes('similipal') || nameLower.includes('chhau')
  ) {
    return REGIONAL_FOOD_DATABASE.mayurbhanj;
  }

  // 7. Ganjam Match
  if (
    locLower.includes('ganjam') || locLower.includes('berhampur') || 
    locLower.includes('gopalpur') || locLower.includes('gajapati') ||
    nameLower.includes('tara tarini') || nameLower.includes('potagarh')
  ) {
    return REGIONAL_FOOD_DATABASE.ganjam;
  }

  // 8. Koraput & Southern Tribal Highlands Match
  if (
    locLower.includes('koraput') || locLower.includes('rayagada') || 
    locLower.includes('malkangiri') || locLower.includes('nabarangpur') ||
    nameLower.includes('gupteswar') || nameLower.includes('deomali')
  ) {
    return REGIONAL_FOOD_DATABASE.koraput;
  }

  // Coordinates Fallback
  if (entity.coordinates && entity.coordinates.length >= 2) {
    const [lat, lon] = entity.coordinates;
    if (lat < 19.4) return REGIONAL_FOOD_DATABASE.koraput;
    if (lon < 84.5) return REGIONAL_FOOD_DATABASE.sambalpur;
    if (lat > 21.3) return REGIONAL_FOOD_DATABASE.mayurbhanj;
    if (lon > 85.5 && lat < 20.1) return REGIONAL_FOOD_DATABASE.puri;
    if (lat >= 20.4) return REGIONAL_FOOD_DATABASE.cuttack;
  }

  // General Pan-Odisha default
  return REGIONAL_FOOD_DATABASE.bhubaneswar;
};
